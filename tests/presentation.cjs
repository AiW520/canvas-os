const assert = require('node:assert/strict');
const fs = require('node:fs/promises');
const path = require('node:path');
const { pathToFileURL } = require('node:url');
const { chromium } = require('playwright');

(async () => {
  const isolated=await require('./auth-helper.cjs').startIsolated();
  const browser = await chromium.launch({ headless: true, executablePath: process.env.CHROME_PATH || 'C:/Program Files/Google/Chrome/Application/chrome.exe' });
  try {
    const page = await browser.newPage({ viewport: { width: 1600, height: 1000 } });
    const errors = [];
    page.on('pageerror', e => errors.push(e.message));
    const base = isolated.url;
    await isolated.login(page);
    await page.goto(`${base}?view=present`);
    assert.equal(await page.locator('.scene-item').count(), 8);
    await page.locator('#sceneHeadlineInput').fill('测试标题\n第二行');
    await page.locator('#sceneNotesInput').fill('PRIVATE_SPEAKER_NOTE');
    await page.locator('#metricFields input').first().fill('888');
    await page.locator('#metricFields input').first().press('End');
    await page.locator('#metricFields input').first().pressSequentially('99');
    assert.equal(await page.locator('#metricFields input').first().inputValue(), '88899', 'typing must retain focus');
    await page.reload();
    assert.equal(await page.locator('#sceneHeadlineInput').inputValue(), '测试标题\n第二行');
    assert.equal(await page.locator('#sceneNotesInput').inputValue(), 'PRIVATE_SPEAKER_NOTE');
    const original = await page.locator('.scene-item.active').innerText();
    await page.click('#duplicateScene');
    assert.equal(await page.locator('.scene-item').count(), 9);
    await page.click('#sceneUp');
    await page.click('#undoScene');
    assert.match(await page.locator('.scene-item.active').innerText(), /副本/);
    await page.click('#redoScene');
    assert.equal(await page.locator('.scene-item').count(), 9);
    await page.click('#undoScene');
    await page.click('#deleteScene');
    assert.equal(await page.locator('.scene-item').count(), 8);
    await page.click('#undoScene');
    assert.equal(await page.locator('.scene-item').count(), 9);
    await page.click('#undoScene');
    assert.equal(await page.locator('.scene-item').count(), 8);
    assert.equal(await page.locator('.scene-item.active').innerText(), original);
    await page.locator('#sceneLayoutInput').selectOption('live');
    const before = await page.locator('.forecast-total').innerText();
    await page.locator('.live-control input').fill('35');
    assert.notEqual(await page.locator('.forecast-total').innerText(), before);
    assert.match(await page.locator('[data-id=app] > p').innerText(), /35%/);
    await page.click('#nextScene');
    assert.equal(await page.locator('.live-control input').inputValue(), '35');
    await page.click('#publishPresentation');
    assert.match(await page.locator('#releaseStatus').innerText(), /发布检查/);
    assert.equal(await page.locator('#releaseIssues span').count(), 0);
    await page.click('#closeReleaseDialog');
    await page.click('#publishPresentation');
    await page.click('#freezeDeck');
    await page.getByRole('button', { name: '本地预览', exact: true }).click();
    await page.frameLocator('#releaseList iframe').locator('#standaloneSlide .slide-title').waitFor();
    await page.click('#closeReleaseDialog');
    await page.locator('#sceneHeadlineInput').fill('后续修改');
    await page.click('#publishPresentation');
    await page.getByRole('button', { name: '恢复到草稿', exact: true }).click();
    assert.equal(await page.locator('.scene-item').count(), 8);
    assert.equal(await page.locator('#sceneHeadlineInput').inputValue(), '健康计划不该\n从一张表开始。');
    await page.locator('.scene-item').nth(3).click();
    assert.equal(await page.locator('#sceneHeadlineInput').inputValue(), '测试标题\n第二行');
    // Malformed import must not replace the working deck.
    await page.locator('#deckFileInput').setInputFiles({ name: 'broken.json', mimeType: 'application/json', buffer: Buffer.from('{"version":3,"scenes":[],"objects":{}}') });
    await page.waitForFunction(() => document.getElementById('presentationSaveState').textContent.startsWith('导入失败'));
    assert.equal(await page.locator('.scene-item').count(), 8);
    // Backup/import round trip and hostile strings must remain plain text.
    const backupPromise = page.waitForEvent('download'); await page.click('#backupDeck');
    const backup = await backupPromise;
    const data = JSON.parse(await fs.readFile(await backup.path(), 'utf8'));
    data.scenes[0].headline = '</script><img src=x onerror="window.XSS=1">';
    data.scenes[0].copy = '<script>window.XSS=2</script>';
    await page.locator('#deckFileInput').setInputFiles({ name: 'safe-text.json', mimeType: 'application/json', buffer: Buffer.from(JSON.stringify(data)) });
    await page.waitForFunction(() => document.getElementById('presentationSaveState').textContent === '已导入并保存');
    assert.equal(await page.evaluate(() => window.XSS), undefined);
    assert.equal(await page.locator('#slideRoot img').count(), 0);
    assert.match(await page.locator('#slideRoot .slide-title').innerText(), /onerror/);
    const downloadPromise = page.waitForEvent('download'); await page.click('#exportPresentation');
    const download = await downloadPromise;
    const exportPath = path.resolve('qa/export-regression.html');
    await fs.mkdir(path.dirname(exportPath), { recursive: true }); await download.saveAs(exportPath);
    const html = await fs.readFile(exportPath, 'utf8');
    assert.ok(!html.includes('PRIVATE_SPEAKER_NOTE'), 'speaker notes leaked to audience');
    const offline = await browser.newContext({ offline: true, viewport: { width: 1280, height: 800 } });
    const player = await offline.newPage(); player.on('pageerror', e => errors.push(e.message));
    await player.goto(pathToFileURL(exportPath).href);
    assert.equal(await player.evaluate(() => window.XSS), undefined);
    assert.equal(await player.locator('#playerCounter').innerText(), '1 / 8');
    await player.click('#playerNext');assert.equal(await player.locator('#playerCounter').innerText(), '2 / 8');
    for(let i=0;i<3;i++) await player.click('#playerNext');
    await player.locator('#standaloneSlide .live-control input').fill('42');
    assert.equal(await player.locator('#standaloneSlide .live-control output').innerText(), '42%');
    assert.equal(await player.locator('#printSlides .slide').count(), 8);
    await offline.close();
    // Save errors are visible and never replace the last persisted version.
    const saved = await page.evaluate(() => localStorage.getItem('canvas-os-project-v3'));
    await page.evaluate(() => { Storage.prototype.setItem = () => { throw new DOMException('quota', 'QuotaExceededError'); }; });
    await page.locator('#sceneTitleInput').fill('不能保存');
    assert.match(await page.locator('#presentationSaveState').innerText(), /保存失败/);
    assert.equal(await page.evaluate(() => localStorage.getItem('canvas-os-project-v3')), saved);
    // Timing and keyboard edits use a fresh isolated context.
    const timing = await browser.newPage(); await isolated.login(timing);await timing.goto(`${base}?view=present`);
    await timing.locator('#sceneDurationInput').fill('5');
    await timing.locator('#sceneNotesInput').focus();
    const counter = await timing.locator('#sceneCounter').innerText();
    await timing.keyboard.press('ArrowRight');assert.equal(await timing.locator('#sceneCounter').innerText(),counter);
    await timing.click('#playScene');await timing.waitForTimeout(5500);
    assert.match(await timing.locator('#sceneCounter').innerText(), /05/);
    await timing.click('#playScene');
    const paused = await timing.locator('#sceneTimer').innerText();await timing.waitForTimeout(500);
    assert.equal(await timing.locator('#sceneTimer').innerText(),paused);
    await timing.keyboard.press('Escape');
    assert.equal(await timing.locator('#presentationOverlay').getAttribute('aria-hidden'),'true');
    assert.deepEqual(errors, []);
    console.log('PASS: edit/persist, focus, reorder/undo, shared live data, snapshots, invalid import, JSON round trip, HTML escaping, offline export, private notes, storage failures, playback and keyboard.');
  } finally { await browser.close();isolated.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
